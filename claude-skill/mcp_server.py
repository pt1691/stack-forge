@mcp.tool()
def generate_terragrunt_project(
    name: str,
    organization: str,
    stacks_json: str,
    output_dir: str = "infrastructure",
    default_region: str = "us-west-2",
    environments: str = "dev,staging,prod",
    write_to_disk: bool = False,
    disk_base_path: str = ".",
) -> str:
    """
    Generate a complete Terragrunt project with all stacks and modules.

    Args:
        name: Project name (e.g. 'data-platform')
        organization: Organization name (e.g. 'acmecorp')
        stacks_json: JSON array of stack definitions. Each stack:
            {
              "name": "network",
              "environment": "dev",
              "region": "us-west-2",
              "resources": [
                {
                  "name": "main-vpc",
                  "type": "vpc",
                  "variables": {"vpc_cidr": "10.0.0.0/16", "az_count": 3},
                  "depends_on": []
                }
              ]
            }
        output_dir: Output directory name within the project (default: 'infrastructure')
        default_region: Default AWS region (default: 'us-west-2')
        environments: Comma-separated environments (default: 'dev,staging,prod')
        write_to_disk: If True, write files to disk at disk_base_path
        disk_base_path: Base directory to write files to (default: current dir)

    Returns:
        Summary of generated files with their contents (or paths if written to disk).
    """
    # Parse stacks
    try:
        stacks_raw = json.loads(stacks_json)
    except json.JSONDecodeError as e:
        return f"ERROR: Invalid stacks_json: {e}"

    envs = [Environment(e.strip()) for e in environments.split(",")]

    stacks = []
    for s in stacks_raw:
        resources = []
        for r in s.get("resources", []):
            resources.append(ResourceConfig(
                name=r["name"],
                type=ResourceType(r["type"]),
                variables=r.get("variables", {}),
                depends_on=r.get("depends_on", []),
            ))
        stacks.append(StackConfig(
            name=s["name"],
            environment=Environment(s.get("environment", "dev")),
            region=s.get("region", default_region),
            resources=resources,
        ))

    project = ProjectConfig(
        name=name,
        organization=organization,
        environments=envs,
        default_region=default_region,
        stacks=stacks,
        output_dir=output_dir,
    )

    files = _write_project(project)

    if write_to_disk:
        base = Path(disk_base_path)
        written = []
        for rel_path, content in files.items():
            full_path = base / rel_path
            full_path.parent.mkdir(parents=True, exist_ok=True)
            full_path.write_text(content)
            written.append(str(full_path))
        return f"✅ Generated {len(written)} files under {base}:\n" + "\n".join(f"  - {p}" for p in sorted(written))
    else:
        # Return file contents for Claude to present
        parts = [f"Generated {len(files)} files:\n"]
        for rel_path, content in sorted(files.items()):
            parts.append(f"### `{rel_path}`\n```hcl\n{content}\n```\n")
        return "\n".join(parts)


@mcp.tool()
def generate_terraform_module(
    resource_type: str,
    name: str = "example",
) -> str:
    """
    Generate a single Terraform module (main.tf, variables.tf, outputs.tf) for a resource type.

    Args:
        resource_type: One of: vpc, s3_bucket, eks, rds, dynamodb, lambda, iam_role, security_group, secrets_manager, ecr
        name: Resource name to use in the template

    Returns:
        The complete Terraform module files.
    """
    rt = resource_type.lower()
    if rt not in TERRAFORM_TEMPLATES:
        return f"ERROR: Unknown resource type '{rt}'. Use list_resource_types to see options."

    parts = [f"## Terraform Module: {rt}\n"]
    parts.append(f"### `modules/{rt}/main.tf`\n```hcl\n{TERRAFORM_TEMPLATES[rt]}\n```\n")
    if rt in VARIABLES_TEMPLATES:
        parts.append(f"### `modules/{rt}/variables.tf`\n```hcl\n{VARIABLES_TEMPLATES[rt]}\n```\n")
    if rt in OUTPUTS_TEMPLATES:
        parts.append(f"### `modules/{rt}/outputs.tf`\n```hcl\n{OUTPUTS_TEMPLATES[rt]}\n```\n")
    return "\n".join(parts)


