    """
    Generate a single child terragrunt.hcl file for a resource.

    Args:
        resource_name: Name of the resource (e.g. 'main-vpc')
        resource_type: Resource type (e.g. 'vpc', 'eks', 'rds')
        project_name: Project name
        organization: Organization name
        environment: Environment (dev, staging, prod)
        region: AWS region
        variables_json: JSON object of input variables
        depends_on: Comma-separated list of dependency resource types (e.g. 'vpc,security_group')

    Returns:
        The terragrunt.hcl file content.
    """
    try:
        variables = json.loads(variables_json)
    except json.JSONDecodeError as e:
        return f"ERROR: Invalid variables_json: {e}"

    deps = [d.strip() for d in depends_on.split(",") if d.strip()]

    resource = ResourceConfig(
        name=resource_name,
        type=ResourceType(resource_type),
        variables=variables,
        depends_on=deps,
    )

    project = ProjectConfig(
        name=project_name,
        organization=organization,
        default_region=region,
    )

    content = _generate_child_terragrunt(resource, project, environment)
    return f"### `live/{environment}/{region}/{RESOURCE_CATEGORY.get(resource_type, 'general')}/{resource_name}/terragrunt.hcl`\n```hcl\n{content}\n```"


