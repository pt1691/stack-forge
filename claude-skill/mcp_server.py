def _generate_env_hcl(env: str) -> str:
    return f'locals {{\n  environment = "{env}"\n}}\n'


def _generate_region_hcl(region: str) -> str:
    return f'locals {{\n  aws_region = "{region}"\n}}\n'


def _generate_child_terragrunt(
    resource: ResourceConfig,
    project: ProjectConfig,
    env: str,
) -> str:
    """Generate a child terragrunt.hcl for a specific resource."""
    resource_type = resource.type.value
    category = RESOURCE_CATEGORY.get(resource_type, "general")

    lines = [
        "# Terragrunt Configuration",
        f"# Resource: {resource.name} ({resource_type})",
        "# Generated by Terragrunt Forge",
        "",
        'include "root" {',
        "  path = find_in_parent_folders()",
        "}",
        "",
        "terraform {",
        f'  source = "${{dirname(find_in_parent_folders())}}//modules/{resource_type}"',
        "}",
        "",
    ]

    # Add dependency blocks
    for dep in resource.depends_on:
        dep_type = dep  # could be a resource type or name
        dep_category = RESOURCE_CATEGORY.get(dep_type, "general")
        lines.extend([
            f'dependency "{dep}" {{',
            f'  config_path = "../../{dep_category}/{dep}"',
            "",
            "  mock_outputs = {",
        ])
        # Add common mock outputs based on dependency type
        if dep in ("vpc",):
            lines.extend([
                '    vpc_id             = "vpc-mock12345"',
                '    private_subnet_ids = ["subnet-mock1", "subnet-mock2", "subnet-mock3"]',
                '    public_subnet_ids  = ["subnet-mock4", "subnet-mock5", "subnet-mock6"]',
            ])
        elif dep in ("security_group",):
            lines.append('    security_group_id = "sg-mock12345"')
        else:
            lines.append(f'    {dep}_id = "mock-{dep}-id"')

        lines.extend([
            "  }",
            '  mock_outputs_allowed_terraform_commands = ["validate", "plan"]',
            "}",
            "",
        ])

    # Inputs
    lines.append("inputs = {")
    lines.append(f'  name = "{resource.name}"')

    # Add dependency references in inputs
    for dep in resource.depends_on:
        if dep == "vpc":
            lines.append(f"  vpc_id     = dependency.{dep}.outputs.vpc_id")
            lines.append(f"  subnet_ids = dependency.{dep}.outputs.private_subnet_ids")

    # Add resource-specific variables
    for key, value in resource.variables.items():
        if isinstance(value, str):
            lines.append(f'  {key} = "{value}"')
        elif isinstance(value, bool):
            lines.append(f"  {key} = {str(value).lower()}")
        elif isinstance(value, (int, float)):
            lines.append(f"  {key} = {value}")
        elif isinstance(value, list):
            items = ", ".join(f'"{v}"' if isinstance(v, str) else str(v) for v in value)
            lines.append(f"  {key} = [{items}]")
        else:
            lines.append(f"  {key} = {json.dumps(value)}")

    lines.append("}")
    lines.append("")

    return "\n".join(lines)


def _write_project(project: ProjectConfig) -> dict[str, str]:
    """Generate all files for a project. Returns dict of relative path → content."""
    files: dict[str, str] = {}
    base = project.output_dir

    # Root terragrunt.hcl
    files[f"{base}/terragrunt.hcl"] = _generate_root_terragrunt(project)

    # Empty.hcl fallback
    files[f"{base}/empty.hcl"] = ""

    # Collect all unique resource types to generate modules
    resource_types_used: set[str] = set()

    for stack in project.stacks:
        env = stack.environment.value
        region = stack.region

        # env.hcl
        files[f"{base}/live/{env}/env.hcl"] = _generate_env_hcl(env)

        # region.hcl
        files[f"{base}/live/{env}/{region}/region.hcl"] = _generate_region_hcl(region)

        for resource in stack.resources:
            rt = resource.type.value
            resource_types_used.add(rt)
            category = RESOURCE_CATEGORY.get(rt, "general")

            # Child terragrunt.hcl
            child_path = f"{base}/live/{env}/{region}/{category}/{resource.name}/terragrunt.hcl"
            files[child_path] = _generate_child_terragrunt(resource, project, env)

    # Generate Terraform modules for each resource type used
    for rt in resource_types_used:
        if rt in TERRAFORM_TEMPLATES:
            files[f"{base}/modules/{rt}/main.tf"] = TERRAFORM_TEMPLATES[rt]
        if rt in VARIABLES_TEMPLATES:
            files[f"{base}/modules/{rt}/variables.tf"] = VARIABLES_TEMPLATES[rt]
        if rt in OUTPUTS_TEMPLATES:
            files[f"{base}/modules/{rt}/outputs.tf"] = OUTPUTS_TEMPLATES[rt]

    return files


